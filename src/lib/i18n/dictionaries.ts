const dictionaries: Record<Locale, Dict> = { sl, en };

export function getDictionary(locale: Locale): Dict {
  return dictionaries[locale] ?? sl;
}

/** Tiny interpolation: fill("Hi {name}", { name: "Ana" }) */
export function fill(
  template: string,
  vars: Record<string, string | number>,
): string {
  return template.replace(/\{(\w+)\}/g, (_, k: string) =>
    vars[k] !== undefined ? String(vars[k]) : `{${k}}`,
  );
}

/** Localized question label with fallback to the config's English label. */
export function questionLabel(dict: Dict, key: string, fallback: string): string {
  return dict.questions[key]?.label ?? fallback;
}

export function questionAnchors(
  dict: Dict,
  key: string,
  fallback?: [string, string],
): [string, string] | undefined {
  return dict.questions[key]?.anchors ?? fallback;
}

export function questionOption(
  dict: Dict,
  key: string,
  value: string,
  fallback: string,
): string {
  return dict.questions[key]?.options?.[value] ?? fallback;
}
